int	ft_atoi(const char *nptr)
{
	int	i;
	int	u;
	int	signe;

	i = 0;
	u = 0;
	signe = 1;
	while (nptr[i] == ' ' || (nptr[i] >= 9 && nptr[i] <= 13))
		i++;
	if (nptr[i] == '-' || nptr[i] == '+')
	{
		if (nptr[i] == '-')
			signe = -1;
		i++;
	}
	while (nptr[i] >= '0' && nptr[i] <= '9')
	{
		u = u * 10 + nptr[i] - 48;
		i++;
	}
	return (u * signe);
}
